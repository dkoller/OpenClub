#!/usr/bin/env bash
# Disposable synthetic-only database backup/restore verification.
set -euo pipefail

if [[ "${1:-}" != "--synthetic-only" || $# -ne 1 ]]; then
  echo "Usage: bash dev/verify-synthetic-restore.sh --synthetic-only" >&2
  exit 2
fi
command -v docker >/dev/null || { echo "Docker is required" >&2; exit 1; }
docker compose version >/dev/null

# Keep the dump outside the checkout and inaccessible to other local users.
umask 077
work="$(mktemp -d "${TMPDIR:-/tmp}/ocdr.XXXXXXXX")"
run_id="$(basename "$work" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9')"
source_project="source${run_id}"
restore_project="restore${run_id}"
dump="$work/backup.dump"

cleanup() {
  # Both project names are generated by this script; never touch another volume.
  docker compose -p "$restore_project" down --volumes --remove-orphans >/dev/null 2>&1 || true
  docker compose -p "$source_project" down --volumes --remove-orphans >/dev/null 2>&1 || true
  rm -f -- "$dump"
  rmdir -- "$work"
}
trap cleanup EXIT

cd "$(dirname "$0")/.."
echo "Starting disposable synthetic source database"
docker compose -p "$source_project" up -d --build --wait --wait-timeout 180

# This fixture is deliberately fake, with no login identity or active sessions.
docker compose -p "$source_project" exec -T postgres \
  psql -v ON_ERROR_STOP=1 -U openclub -d openclub <<'SQL'
INSERT INTO clubs (id, name, slug) VALUES
  ('11111111-1111-4111-8111-111111111111', 'Synthetic Recovery Club', 'synthetic-recovery');
INSERT INTO members (id, first_name, last_name, date_of_birth, email, phone)
VALUES ('22222222-2222-4222-8222-222222222222', 'Synthetic', 'Member',
        DATE '1990-01-01', 'synthetic@example.invalid', '+41000000000');
INSERT INTO teams (id, name) VALUES
  ('33333333-3333-4333-8333-333333333333', 'Synthetic Team');
INSERT INTO member_team_assignments (team_id, member_id) VALUES
  ('33333333-3333-4333-8333-333333333333',
   '22222222-2222-4222-8222-222222222222');
INSERT INTO club_capability_grants (member_id, capability) VALUES
  ('22222222-2222-4222-8222-222222222222', 'VIEW_TEAMS');
INSERT INTO team_capability_grants (team_id, member_id, capability) VALUES
  ('33333333-3333-4333-8333-333333333333',
   '22222222-2222-4222-8222-222222222222', 'VIEW_TEAMS');
SQL

# Compare the restore's Flyway version count against the actual source, not
# a hardcoded migration number that can go stale after subsequent changes.
migration_count="$(docker compose -p "$source_project" exec -T postgres \
  psql -qAt -v ON_ERROR_STOP=1 -U openclub -d openclub \
  -c 'SELECT COUNT(*) FROM flyway_schema_history WHERE success')"
[[ "$migration_count" =~ ^[0-9]+$ ]] && (( migration_count > 0 ))


docker compose -p "$source_project" exec -T postgres \
  pg_dump -U openclub -d openclub --format=custom --no-owner > "$dump"
test -s "$dump"

# The stock development Compose binds PostgreSQL to port 5432.
# Stop the source without removing its volume before starting the destination.
docker compose -p "$source_project" stop
docker compose -p "$restore_project" up -d --wait --wait-timeout 90 postgres
docker compose -p "$restore_project" exec -T postgres \
  pg_restore --exit-on-error --no-owner --no-privileges \
  -U openclub -d openclub < "$dump"

result="$(docker compose -p "$restore_project" exec -T postgres \
  psql -qAt -v ON_ERROR_STOP=1 -v expected_migrations="$migration_count" \
  -U openclub -d openclub <<'SQL'
SELECT CASE WHEN
  (SELECT COUNT(*) FROM clubs) = 1
  AND (SELECT name FROM clubs) = 'Synthetic Recovery Club'
  AND (SELECT COUNT(*) FROM members WHERE first_name = 'Synthetic'
       AND email = 'synthetic@example.invalid') = 1
  AND (SELECT COUNT(*) FROM member_team_assignments) = 1
  AND (SELECT COUNT(*) FROM club_capability_grants) = 1
  AND (SELECT COUNT(*) FROM team_capability_grants) = 1
  AND (SELECT COUNT(*) FROM flyway_schema_history WHERE success) =
      :'expected_migrations'::integer
THEN 'RESTORE_OK' ELSE 'RESTORE_FAILED' END;
SQL
)"
if [[ "$result" != "RESTORE_OK" ]]; then
  echo "Restore fixture/integrity verification failed: $result" >&2
  exit 1
fi
# A recovered database is only useful if OpenClub can boot against it.
# This starts the real API using the restored Flyway history, not a mock check.
docker compose -p "$restore_project" up -d --build --wait --wait-timeout 180 api
api_health="$(docker compose -p "$restore_project" exec -T api \
  wget -q -O - http://127.0.0.1:8080/health)"
if [[ "$api_health" != '{"status":"ok"}' ]]; then
  echo "API did not start successfully against the restored database" >&2
  exit 1
fi
echo "Synthetic backup, restore, data integrity and API startup verified."
